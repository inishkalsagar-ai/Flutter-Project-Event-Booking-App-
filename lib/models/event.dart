class Event {
  final String id;
  final String title;
  final String category;
  final String location;
  final String date;
  final String time;
  final String price;
  final String description;

  Event({
    required this.id,
    required this.title,
    required this.category,
    required this.location,
    required this.date,
    required this.time,
    required this.price,
    required this.description,
  });
}